function formulaQuestion({
  id,
  question,
  options,
  answer,
  hint,
  formula,
  why,
  steps,
  concept = 'Formula choice',
}) {
  return {
    id,
    concept,
    question,
    options,
    answer,
    explanation: `${formula} ${why}`,
    teaching: {
      hint,
      ask: 'Choose the relationship that contains the useful known values and the requested unknown without adding an unnecessary unknown.',
      rule: formula,
      steps,
      why,
    },
  };
}

