export function getQuizTeaching(question) {
  if (question.teaching) return question.teaching;
  if (question.number && examTeaching[question.number]) return examTeaching[question.number];
  if (lectureTeaching[question.question]) return lectureTeaching[question.question];

  return {
    hint: `Look for the rule used here: ${question.explanation}`,
    ask: 'Identify the given information, the requested quantity, and the rule connecting them.',
    rule: question.explanation,
    steps: [
      'Read the question once for the story and once for the numbers or key words.',
      'Write the relevant rule before choosing an answer.',
      'Apply the rule carefully and compare the result with every option.',
    ],
    why: `The correct choice follows the stated rule: ${question.explanation}`,
  };
}
